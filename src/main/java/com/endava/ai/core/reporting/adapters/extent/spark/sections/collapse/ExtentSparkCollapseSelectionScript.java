package com.endava.ai.core.reporting.adapters.extent.spark.sections.collapse;

import com.endava.ai.core.reporting.adapters.extent.tokens.ExtentDataAttributes;
import com.endava.ai.core.reporting.adapters.extent.tokens.ExtentMarkers;
import com.endava.ai.core.reporting.adapters.extent.mode.ExtentReportModeType;

final class ExtentSparkCollapseSelectionScript {

    private ExtentSparkCollapseSelectionScript() {}

    static String javascript() {
        return "function activeDetailBody(){"
                + "var bodies=Array.prototype.slice.call(document.querySelectorAll('.test-content .detail-body'));"
                + "return bodies.find(visible)||bodies[bodies.length-1]||null;"
                + "}"
                + "function showTestItem(item){"
                + "var content=activeDetailBody();"
                + "var source=item&&Array.prototype.slice.call(item.children).find(function(child){"
                + "return child.classList&&child.classList.contains('test-contents');"
                + "});"
                + "if(!content||!source){return false;}"
                + "content.innerHTML=source.innerHTML;"
                + "document.querySelectorAll('.test-list li.test-item').forEach(function(candidate){candidate.classList.remove('active');});"
                + "item.classList.add('active');"
                + "setTimeout(window.collapseExtentTreeByDefault,80);"
                + "return true;"
                + "}"
                + "function sourceForTestItem(item){"
                + "return item&&Array.prototype.slice.call(item.children).find(function(child){"
                + "return child.classList&&child.classList.contains('test-contents');"
                + "});"
                + "}"
                + "function directHeader(card){return card&&Array.prototype.slice.call(card.children)"
                + ".find(function(child){return child.classList&&child.classList.contains('card-header');});}"
                + "function statusFromHeader(card){"
                + "var text=normalizedText(directHeader(card));"
                + "if(/\\bSkip(ped)?\\b/i.test(text)){return 'skip';}"
                + "if(/\\bFail(ed)?\\b/i.test(text)){return 'fail';}"
                + "if(/\\bPass(ed)?\\b/i.test(text)){return 'pass';}"
                + "return '';"
                + "}"
                + "function runtimeInvocationCards(source){"
                + "if(!source){return [];}"
                + "var direct=Array.prototype.slice.call(source.querySelectorAll(':scope > .mt-4 > .accordion > .card'));"
                + "if(direct.length){return direct;}"
                + "return Array.prototype.slice.call(source.querySelectorAll('.accordion[role=\"tablist\"] > .card')).filter(function(card){"
                + "return !card.parentElement||!card.parentElement.closest('.card');"
                + "});"
                + "}"
                + "function sourceHasStatus(source,status){"
                + "return runtimeInvocationCards(source).some(function(card){"
                + "return statusFromHeader(card)===status;"
                + "});"
                + "}"
                + "function itemStatus(item){"
                + "var status=item&&item.getAttribute&&item.getAttribute('status');"
                + "return status==='skipped'?'skip':(status||'');"
                + "}"
                + "function statusCardsForItem(source,status){return runtimeInvocationCards(source)"
                + ".filter(function(card){return statusFromHeader(card)===status;});}"
                + "function componentAdapterMode(){"
                + "var mode=document.getElementById('" + ExtentMarkers.REPORT_MODE + "');"
                + "return mode&&mode.getAttribute('" + ExtentDataAttributes.REPORT_MODE + "')==='"
                + ExtentReportModeType.COMPONENT_ADAPTER.value() + "';"
                + "}"
                + "function statusSelectionClone(node){"
                + "var clone=node.cloneNode(true);"
                + "[clone].concat(Array.prototype.slice.call(clone.querySelectorAll('*'))).forEach(function(element){"
                + "element.classList.remove('d-none','hide');"
                + "if(element.style&&element.style.display==='none'){element.style.display='';}"
                + "});"
                + "clone.querySelectorAll('.collapse').forEach(function(collapse){collapse.classList.add('show');});"
                + "clone.querySelectorAll('[aria-expanded]').forEach(function(toggle){toggle.setAttribute('aria-expanded','true');});"
                + "clone.querySelectorAll('textarea').forEach(function(textarea){"
                + "var pre=document.createElement('pre');"
                + "pre.className=textarea.className||'code-block';"
                + "pre.textContent=textarea.value||textarea.textContent||'';"
                + "textarea.parentNode.replaceChild(pre,textarea);"
                + "});"
                + "return clone;"
                + "}"
                + "function componentStatusSelectionClone(node){"
                + "var clone=statusSelectionClone(node);"
                + "var textareaText=Array.prototype.slice.call(node.querySelectorAll('textarea')).map(function(textarea){"
                + "return textarea.value||textarea.textContent||'';"
                + "}).filter(Boolean).join('\\n');"
                + "var fullText=[normalizedText(node),textareaText].filter(Boolean).join('\\n');"
                + "if(fullText&&normalizedText(clone).indexOf(fullText)<0){"
                + "var details=document.createElement('div');"
                + "details.className='atf-runtime-status-selection-source-text';"
                + "details.textContent=fullText;"
                + "clone.appendChild(details);"
                + "}"
                + "return clone;"
                + "}"
                + "function isClassTestItem(item){"
                + "var source=sourceForTestItem(item);"
                + "return !!(source&&source.innerHTML.indexOf('#test-id=')>=0);"
                + "}"
                + "function itemName(item){return normalizedText(item.querySelector('.test-detail .name')||item);}"
                + "function itemHasExactTagToken(item,tag){"
                + "var nodes=Array.prototype.slice.call(item.querySelectorAll('.badge,.node-attr span,span'));"
                + "return nodes.some(function(node){return normalizedText(node)===tag;});"
                + "}"
                + "function itemMatchesTag(item,tag){"
                + "var name=itemName(item);"
                + "return name.indexOf(tag)>=0||itemHasExactTagToken(item,tag);"
                + "}"
                + "function showTagCollection(tag,items){"
                + "var content=activeDetailBody();"
                + "if(!content||!items.length){return false;}"
                + "document.querySelectorAll('.test-list li.test-item').forEach(function(candidate){candidate.classList.remove('active');});"
                + "items.forEach(function(item){item.classList.add('active');});"
                + "var html='<div class=\"test-contents atf-runtime-tag-selection\">'"
                + "+'<div class=\"p-v-10\"><h5 class=\"test-status text-pass\">'+escapeHtml(tag)+'</h5>'"
                + "+'<span class=\"badge badge-default\">'+items.length+' matching test classes</span></div>';"
                + "items.forEach(function(item){"
                + "var source=sourceForTestItem(item);"
                + "html+='<div class=\"atf-runtime-tag-selected-item m-t-15\">';"
                + "html+='<div class=\"badge badge-primary m-b-10\">'+escapeHtml(itemName(item))+'</div>';"
                + "html+=source?source.innerHTML:escapeHtml(normalizedText(item));"
                + "html+='</div>';"
                + "});"
                + "html+='</div>';"
                + "content.innerHTML=html;"
                + "setTimeout(window.collapseExtentTreeByDefault,80);"
                + "return true;"
                + "}"
                + "function showStatusCollection(status,label,cards){"
                + "var content=activeDetailBody();"
                + "if(!content||!cards.length){return false;}"
                + "var html='<div class=\"test-contents atf-runtime-status-selection\">'"
                + "+'<div class=\"p-v-10\"><h5 class=\"test-status text-'+(status==='fail'?'fail':status==='skip'?'skip':'pass')+'\">'"
                + "+escapeHtml(label)+'</h5><span class=\"badge badge-default\">'+cards.length+' matching test case(s)</span></div>';"
                + "cards.forEach(function(card){"
                + "html+='<div class=\"atf-runtime-tag-selected-item m-t-15\">'+card.outerHTML+'</div>';"
                + "});"
                + "html+='</div>';"
                + "content.innerHTML=html;"
                + "setTimeout(window.collapseExtentTreeByDefault,80);"
                + "return true;"
                + "}"
                + "function selectVisibleTestsForStatus(status,label){"
                + "if(!status||status==='clear'){return;}"
                + "var allItems=Array.prototype.slice.call(document.querySelectorAll('.test-list li.test-item'));"
                + "var matchedItems=[];"
                + "var matchedCards=[];"
                + "allItems.forEach(function(item){"
                + "var source=sourceForTestItem(item);"
                + "var cards=statusCardsForItem(source,status);"
                + "var matches=cards.length>0||itemStatus(item)===status||sourceHasStatus(source,status);"
                + "if(matches){matchedItems.push(item);}"
                + "if(componentAdapterMode()&&itemStatus(item)===status&&source){"
                + "matchedCards.push(componentStatusSelectionClone(source));"
                + "}else if(cards.length){"
                + "cards.forEach(function(card){matchedCards.push(statusSelectionClone(card));});"
                + "}else if(matches&&source){"
                + "matchedCards.push(statusSelectionClone(source));"
                + "}"
                + "});"
                + "allItems.forEach(function(item){item.style.display=matchedItems.indexOf(item)>=0?'':'none';});"
                + "document.querySelectorAll('.test-list li.test-item').forEach(function(candidate){candidate.classList.remove('active');});"
                + "matchedItems.forEach(function(item){item.classList.add('active');});"
                + "showStatusCollection(status,label||status,matchedCards);"
                + "}"
                + "window.atfSelectExtentStatus=function(status,label){selectVisibleTestsForStatus(status,label);};"
                + "function selectVisibleTestsForTag(tag){"
                + "if(!tag){return;}"
                + "var allItems=Array.prototype.slice.call(document.querySelectorAll('.test-list li.test-item'));"
                + "var items=allItems.filter(isClassTestItem);"
                + "var matched=items.filter(function(candidate){return itemMatchesTag(candidate,tag);});"
                + "allItems.forEach(function(candidate){"
                + "candidate.style.display=matched.indexOf(candidate)>=0?'':'none';"
                + "});"
                + "if(!matched.length){return;}"
                + "showTagCollection(tag,matched);"
                + "}"
                + "window.atfSelectExtentTag=function(tag){selectVisibleTestsForTag(tag);};";
    }
}
