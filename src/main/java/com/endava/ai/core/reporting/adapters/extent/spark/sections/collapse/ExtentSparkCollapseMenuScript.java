package com.endava.ai.core.reporting.adapters.extent.spark.sections.collapse;

final class ExtentSparkCollapseMenuScript {

    private ExtentSparkCollapseMenuScript() {
    }

    static String javascript() {
        return "function normalizeStatusMenu(){"
                + "var menu=document.querySelector('#status-toggle');"
                + "if(!menu){return;}"
                + "if(!menu.querySelector('.atf-status-filter-label')){"
                + "var label=document.createElement('li');"
                + "label.className='atf-status-filter-label';"
                + "label.textContent='Status';"
                + "menu.insertBefore(label,menu.firstChild);"
                + "}"
                + "function ensureStatusItem(status,label,marker,beforeSelector){"
                + "if(menu.querySelector('[status=\"'+status+'\"]')){return;}"
                + "var item=document.createElement('a');"
                + "item.className='dropdown-item';"
                + "item.setAttribute('status',status);"
                + "item.setAttribute('href','#');"
                + "item.innerHTML='<span>'+label+'</span><span class=\"status '+marker+'\"></span>';"
                + "menu.insertBefore(item,menu.querySelector(beforeSelector)||menu.querySelector('[status=\"clear\"]')||null);"
                + "}"
                + "function normalizeStatusItem(status,label,marker){"
                + "var item=menu.querySelector('[status=\"'+status+'\"]')"
                + "||(status==='skip'?menu.querySelector('[status=\"skipped\"]'):null);"
                + "if(!item){return;}"
                + "item.classList.add('dropdown-item');"
                + "item.setAttribute('status',status);"
                + "if(!item.getAttribute('href')){item.setAttribute('href','#');}"
                + "item.innerHTML='<span>'+label+'</span><span class=\"status '+marker+'\"></span>';"
                + "}"
                + "function normalizeClearItem(){"
                + "var item=menu.querySelector('[status=\"clear\"]');"
                + "if(!item){return;}"
                + "item.classList.add('dropdown-item');"
                + "item.setAttribute('status','clear');"
                + "if(!item.getAttribute('href')){item.setAttribute('href','#');}"
                + "item.innerHTML='<span>Clear</span><span class=\"pull-right\"><i class=\"fa fa-times\"></i></span>';"
                + "}"
                + "ensureStatusItem('pass','Pass','success','[status=\"fail\"],[status=\"skip\"],[status=\"skipped\"],[status=\"clear\"]');"
                + "ensureStatusItem('fail','Fail','danger','[status=\"skip\"],[status=\"skipped\"],[status=\"clear\"]');"
                + "if(!menu.querySelector('[status=\"skip\"]')&&!menu.querySelector('[status=\"skipped\"]')){"
                + "ensureStatusItem('skip','Skip','warning','[status=\"clear\"]');"
                + "}"
                + "normalizeStatusItem('pass','Pass','success');"
                + "normalizeStatusItem('fail','Fail','danger');"
                + "normalizeStatusItem('skip','Skip','warning');"
                + "normalizeClearItem();"
                + "}"
                + "function closeStatusMenu(){"
                + "var menu=document.querySelector('#status-toggle');"
                + "if(!menu){return;}"
                + "menu.classList.remove('show');"
                + "menu.style.display='';"
                + "var trigger=document.querySelector('.test-list-tools .fa.fa-exclamation-circle');"
                + "var button=trigger&&trigger.closest('a,button');"
                + "if(button){button.setAttribute('aria-expanded','false');}"
                + "}"
                + "function closeTagMenu(){"
                + "var menu=document.querySelector('#tag-toggle');"
                + "if(!menu){return;}"
                + "menu.classList.remove('show');"
                + "menu.style.display='';"
                + "var trigger=document.querySelector('.test-list-tools .fa.fa-bug');"
                + "var button=trigger&&trigger.closest('a,button');"
                + "if(button){button.setAttribute('aria-expanded','false');}"
                + "}"
                + "function closeRuntimeMenus(){closeStatusMenu();closeTagMenu();}";
    }
}
