package com.endava.ai.ui.core.engine.selenium.element.selectors;

final class SeleniumSelectorScripts {
    static final String FIND_MATCHES =
            "const selector = arguments[0];"
                    + "const visible = el => !!(el && (el.offsetWidth || el.offsetHeight || el.getClientRects().length));"
                    + "const norm = el => (el && (el.innerText || el.textContent) || '').replace(/\\s+/g, ' ').trim();"
                    + "function splitTopLevel(value, delimiter) {"
                    + "  const parts=[]; let buf=''; let quote=null; let depth=0;"
                    + "  for (let i=0; i<value.length; i++) {"
                    + "    const ch=value[i];"
                    + "    if (quote) { buf += ch; if (ch === quote && value[i - 1] !== '\\\\') quote = null; continue; }"
                    + "    if (ch === '\\'' || ch === '\"') { quote = ch; buf += ch; continue; }"
                    + "    if (ch === '(' || ch === '[') depth++;"
                    + "    if (ch === ')' || ch === ']') depth--;"
                    + "    if (ch === delimiter && depth === 0) { if (buf.trim()) parts.push(buf.trim()); buf=''; continue; }"
                    + "    buf += ch;"
                    + "  }"
                    + "  if (buf.trim()) parts.push(buf.trim());"
                    + "  return parts;"
                    + "}"
                    + "function splitDescendant(value) {"
                    + "  const parts=[]; let buf=''; let quote=null; let depth=0;"
                    + "  for (let i=0; i<value.length; i++) {"
                    + "    const ch=value[i];"
                    + "    if (quote) { buf += ch; if (ch === quote && value[i - 1] !== '\\\\') quote = null; continue; }"
                    + "    if (ch === '\\'' || ch === '\"') { quote = ch; buf += ch; continue; }"
                    + "    if (ch === '(' || ch === '[') depth++;"
                    + "    if (ch === ')' || ch === ']') depth--;"
                    + "    if (/\\s/.test(ch) && depth === 0) { if (buf.trim()) parts.push(buf.trim()); buf=''; continue; }"
                    + "    buf += ch;"
                    + "  }"
                    + "  if (buf.trim()) parts.push(buf.trim());"
                    + "  return parts;"
                    + "}"
                    + "function parseSegment(segment) {"
                    + "  const texts=[];"
                    + "  let requireVisible = false;"
                    + "  let css = segment.replace(/:visible\\b/g, function(){ requireVisible = true; return ''; });"
                    + "  css = css.replace(/:has-text\\((['\"])(.*?)\\1\\)/g, function(_, q, text){ texts.push(text); return ''; });"
                    + "  return { css: css.trim() || '*', texts: texts, requireVisible: requireVisible };"
                    + "}"
                    + "function queryWithin(context, css) {"
                    + "  try { return Array.from(context.querySelectorAll(css)); } catch (err) { return []; }"
                    + "}"
                    + "function matchesSegment(element, spec) {"
                    + "  if (spec.requireVisible && !visible(element)) return false;"
                    + "  return spec.texts.every(text => norm(element).includes(text));"
                    + "}"
                    + "function textMatches(text) {"
                    + "  const matches = Array.from(document.querySelectorAll('body *')).filter(el => visible(el) && norm(el).includes(text));"
                    + "  const specific = matches.filter(el => !Array.from(el.children).some(child => visible(child) && norm(child).includes(text)));"
                    + "  return specific.length ? specific : matches;"
                    + "}"
                    + "function findPart(part) {"
                    + "  if (part.startsWith('text=')) {"
                    + "    return textMatches(part.substring(5));"
                    + "  }"
                    + "  const segments = splitDescendant(part).map(parseSegment);"
                    + "  let contexts = [document];"
                    + "  for (const segment of segments) {"
                    + "    let next = [];"
                    + "    for (const context of contexts) {"
                    + "      next = next.concat(queryWithin(context, segment.css).filter(el => matchesSegment(el, segment)));"
                    + "    }"
                    + "    contexts = next;"
                    + "  }"
                    + "  return contexts;"
                    + "}"
                    + "const all=[];"
                    + "for (const part of splitTopLevel(selector, ',')) { all.push(...findPart(part)); }"
                    + "return Array.from(new Set(all));";
    static final String HIT_TEST_VISIBLE =
            "const el = arguments[0];"
                    + "if (!el) return false;"
                    + "const rect = el.getBoundingClientRect();"
                    + "if (!rect.width || !rect.height) return false;"
                    + "const x = rect.left + rect.width / 2;"
                    + "const y = rect.top + rect.height / 2;"
                    + "if (x < 0 || y < 0 || x > window.innerWidth || y > window.innerHeight) return false;"
                    + "const top = document.elementFromPoint(x, y);"
                    + "return top === el || el.contains(top);";
    static final String BODY_TEXT =
            "return (document.body && (document.body.innerText || document.body.textContent) || '')"
                    + ".replace(/\\s+/g, ' ').trim();";

    private SeleniumSelectorScripts() {
    }
}
